import 'package:flutter/material.dart';
import 'package:nativebind/nativebind.dart';

import 'app.dart';
import 'nativebind/nativebind_modules.dart'; // generated by `dart run nativebind_generator`

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  try {
    // Loads the C++ library, checks that the generated Dart code matches it
    // and loads the complete state, so the first frame shows real values.
    await NativeBind.start(library: 'libshowcase_backend.so', modules: nativebindModules);
  } on BindException catch (e) {
    runApp(MaterialApp(home: Scaffold(body: Center(child: Text('Backend failed to start:\n\n${e.message}')))));
    return;
  }
  runApp(const ShowcaseApp());
}
