const _sh = '::nativebind::glue::shape';

/// The C++ shape type (see glue.hpp) the generated code asserts a type has.
String _shape(TypeRef t) => switch (t) {
      PrimType(prim: Prim.voidT) => '$_sh::Void',
      PrimType(prim: Prim.boolT) => '$_sh::Bool',
      PrimType(prim: Prim.intT) => '$_sh::Int',
      PrimType(prim: Prim.doubleT) => '$_sh::Double',
      PrimType(prim: Prim.stringT) => '$_sh::String',
      PrimType(prim: Prim.timeT) => '$_sh::Time',
      PrimType(prim: Prim.durationT) => '$_sh::Duration',
      ListType(:final item) => '$_sh::List<${_shape(item)}>',
      OptionalType(:final inner) => '$_sh::Optional<${_shape(inner)}>',
      EnumType(:final decl) => '$_sh::Enum<${decl?.qualified ?? '$_sh::Any'}>',
      StructType(:final decl) => '$_sh::Struct<${decl?.qualified ?? '$_sh::Any'}>',
    };

String _args(Iterable<TypeRef> ts) => '$_sh::Args<${ts.map(_shape).join(', ')}>';
String _argSchema(Iterable<TypeRef> ts) => '(${ts.map((t) => t.schema).join(', ')})';

/// Emits `<name>.nb.cpp` for the modules of one source file.
class CppEmitter {
  CppEmitter(this.analyzer, this.modules,
      {required this.includePath, required this.sourceLabel, this.isExternal = _never, this.refs, this.refHeader});

  /// Typed references for other modules (`<name>.nb.hpp`); their `get()`
  /// functions are defined in this file.
  final CppRefEmitter? refs;
  final String? refHeader;

  static bool _never(String file) => false;

  /// True for types of a NATIVEBIND_DART_LIBRARY header: that library's own
  /// glue registers their codecs, so they are not emitted here.
  final bool Function(String cppFile) isExternal;

  final Analyzer analyzer;
  final List<RModule> modules;

  /// How the glue includes the module source (relative to the glue file).
  final String includePath;
  final String sourceLabel;

  final _b = StringBuffer();

  void _l([String s = '']) => _b.writeln(s);

  String emit() {
    _l('// Generated by nativebind_generator from $sourceLabel. DO NOT EDIT.');
    _l('// The module source is compiled through this file.');
    _l();
    _l('#include ${cppString(includePath)}');
    _l();
    _l('#include <nativebind/glue.hpp>');

    final structs = <StructDecl>[];
    for (final m in modules) {
      for (final s in m.structs) {
        if (s.decl != null && !isExternal(s.decl!.file) && !structs.contains(s.decl)) structs.add(s.decl!);
      }
    }
    if (structs.isNotEmpty) {
      _l();
      _l('// ---------------------------------------------------------------- structs');
      _l();
      _l('namespace {');
      for (final s in structs) {
        _struct(analyzer.structOf(s));
      }
      _l();
      _l('}  // namespace');
    }
    for (final m in modules) {
      _module(m);
    }
    final r = refs;
    if (r != null && refHeader != null) {
      _l();
      _l('// ---------------------------------------------------------------- typed references');
      _l();
      _l('#include ${cppString(refHeader!)}');
      _b.write(r.emitDefinitions());
    }
    return _b.toString();
  }

  void _struct(RStruct s) {
    final q = s.decl.qualified;
    final id = cIdent(q);
    final n = s.fields.length;
    _l();
    for (final f in s.fields) {
      _l('static_assert(::nativebind::glue::hasShape<decltype($q::${f.decl.name}), ${_shape(f.type)}>,');
      _l('              "nativebind_generator read $q::${f.decl.name} as ${f.type.schema}; please report this");');
    }
    _l();
    final names = [for (var k = 0; k < n; k++) 'f$k'].join(', ');
    _l('void nativebind_encode_$id(::nativebind::Writer& w, const void* p) {');
    _l('    const auto& v = *static_cast<const $q*>(p);');
    _l('    // Fails to compile if $q has a field nativebind_generator did not see.');
    _l('    [[maybe_unused]] const auto& [$names] = v;');
    _l('    w.beginStruct($n);');
    for (final f in s.fields) {
      _l('    w.value(v.${f.decl.name});');
    }
    _l('}');
    _l();
    _l('void nativebind_decode_$id(::nativebind::Reader& r, void* p) {');
    _l('    auto& v = *static_cast<$q*>(p);');
    _l('    r.beginStruct($n);');
    for (final f in s.fields) {
      _l('    v.${f.decl.name} = r.value<decltype(v.${f.decl.name})>();');
    }
    _l('}');
    _l();
    _l('const ::nativebind::glue::StructRegistrar<$q> nativebind_struct_$id{');
    _l('    ${cppString(s.decl.name)}, &nativebind_encode_$id, &nativebind_decode_$id};');
  }

  void _module(RModule m) {
    final q = m.decl.qualified;
    final id = cIdent(q);
    final name = m.decl.name;
    final props = m.props.toList();
    final methods = m.methods.toList();

    _l();
    _l('// ---------------------------------------------------------------- $name');
    _l();
    _l('template <>');
    _l('struct nativebind::glue::Invoker<$q> {');
    _l('    using Self = $q;');
    _l('    static constexpr ::nativebind::ModuleOptions options = Self::nativebind_options_;');
    if (props.isEmpty) {
      _l('    static constexpr const ::nativebind::glue::PropDecl* props = nullptr;');
    } else {
      _l('    static constexpr ::nativebind::glue::PropDecl props[] = {');
      for (final p in props) {
        _l('        {${cppString(p.name)}, ::nativebind::tagOf<decltype(Self::${p.name})::value_type>()},');
      }
      _l('    };');
    }
    _l();
    // The generator's reading of every type against the compiler's, nested
    // types included (glue.hpp, "shapes").
    for (final p in props) {
      _l('    static_assert(::nativebind::glue::hasShape<decltype(Self::${p.name})::value_type, ${_shape(p.type)}>,');
      _l('                  "nativebind_generator read $name::${p.name} as ${p.type.schema}; please report this");');
    }
    for (final l in m.lists) {
      _l('    static_assert(::nativebind::glue::hasShape<decltype(Self::${l.name})::value_type, ${_shape(l.item)}>,');
      _l('                  "nativebind_generator read the items of $name::${l.name} as ${l.item.schema}; please report this");');
    }
    for (final sig in m.signals) {
      _l('    static_assert(::nativebind::glue::signalHasShape<decltype(Self::${sig.name}), ${_args(sig.args)}>,');
      _l('                  "nativebind_generator read the arguments of $name::${sig.name} as ${_argSchema(sig.args)}; please report this");');
    }
    for (final f in methods) {
      final params = f.params.map((p) => p.type);
      _l('    static_assert(::nativebind::glue::methodHasShape<&Self::${f.name}, $_sh::Fn<${_shape(f.returns)}, ${_args(params)}>>,');
      _l('                  "nativebind_generator read $name::${f.name} as ${f.returns.schema}${_argSchema(params)}; please report this");');
    }
    for (final e in m.enums) {
      final d = e.decl;
      if (d == null) continue;
      for (final v in d.values) {
        _l('    static_assert(static_cast<long long>(${d.qualified}::${v.name}) == ${v.value}LL,');
        _l('                  "nativebind_generator read ${d.name}::${v.name} as ${v.value}; please report this");');
      }
    }
    if (props.isNotEmpty || m.lists.isNotEmpty || m.signals.isNotEmpty || methods.isNotEmpty || m.enums.any((e) => e.decl != null)) {
      _l();
    }

    _l('    static void invoke(::nativebind::Module& m, uint16_t method, ::nativebind::Reader& args, ::nativebind::Writer& result) {');
    if (methods.isEmpty) {
      _l('        (void)m;');
      _l('        (void)args;');
      _l('        (void)result;');
    } else {
      _l('        auto& self = static_cast<Self&>(m);');
      _l('        switch (method) {');
      for (final (k, meth) in methods.indexed) {
        final permission = meth.permission;
        _l('            case $k:  // ${meth.name}');
        if (permission != null) {
          _l('                ::nativebind::glue::requirePermission(${cppString(name)}, ${cppString(meth.name)},');
          _l('                                                      static_cast<int64_t>($permission));');
        }
        _l('                ::nativebind::glue::call(self, &Self::${meth.name}, args, result);');
        _l('                return;');
      }
      _l('        }');
    }
    _l('        ::nativebind::glue::unknownMethod(${cppString(name)}, method);');
    _l('    }');
    _l('};');
    _l();
    _l('namespace {');
    _l();
    final schema = schemaOf(m, analyzer).split('\n')..removeLast();
    _l('constexpr const char nativebind_schema_$id[] =');
    for (final (k, line) in schema.indexed) {
      _l('    ${cppString('$line\n')}${k == schema.length - 1 ? ';' : ''}');
    }
    _l();
    _l('const ::nativebind::glue::ModuleType nativebind_type_$id{');
    _l('    .name = ${cppString(name)},');
    _l('    .cppType = &typeid($q),');
    _l('    .instanced = ::nativebind::glue::Invoker<$q>::options.instanced,');
    _l('    .order = ::nativebind::glue::Invoker<$q>::options.order,');
    _l('    .create = ::nativebind::glue::factoryFor<$q>(::nativebind::glue::Invoker<$q>::options.instanced),');
    _l('    .invoke = &::nativebind::glue::Invoker<$q>::invoke,');
    _l('    .props = ::nativebind::glue::Invoker<$q>::props,');
    _l('    .propCount = ${props.length},');
    _l('    .listCount = ${m.lists.length},');
    _l('    .signalCount = ${m.signals.length},');
    _l('    .methodCount = ${methods.length},');
    _l('    .schema = nativebind_schema_$id,');
    _l('};');
    _l();
    _l('const ::nativebind::glue::Registrar nativebind_register_$id{nativebind_type_$id};');
    _l();
    _l('}  // namespace');
  }
}

/// Emits `<name>.nb.hpp`: typed references to the props and lists of the
/// modules of one source file, so other module files can use them without
/// string lookups:
///
///     #include "player.nb.hpp"
///     auto player = nativebind::ref::Player::get();   // in onStart
///     double v = player.volume;
///
/// Members whose type is declared in the module's own .cpp cannot be named
/// in the header; they are left out (move such enums into a header).
class CppRefEmitter {
  CppRefEmitter(this.analyzer, this.modules,
      {required this.sourceFile, required this.sourceLabel, required this.includes});

  final Analyzer analyzer;
  final List<RModule> modules;
  final String sourceFile;
  final String sourceLabel;

  /// Include directives of the source, ready to print (`<...>` or `"..."`).
  final List<String> includes;

  static const _stdWords = {
    'std', 'chrono', 'string', 'vector', 'optional', 'system_clock', 'time_point', 'duration', 'ratio', //
    'nanoseconds', 'microseconds', 'milliseconds', 'seconds', 'minutes', 'hours', 'days', 'weeks', 'months', 'years',
    'nano', 'micro', 'milli', 'centi', 'deci', 'kilo', //
    'int8_t', 'int16_t', 'int32_t', 'int64_t', 'uint8_t', 'uint16_t', 'uint32_t', 'uint64_t', 'size_t', 'ptrdiff_t',
    'intptr_t', 'uintptr_t', 'int_least32_t', 'int_fast32_t', 'ssize_t', 'intmax_t', 'uintmax_t', //
    'unsigned', 'signed', 'short', 'long', 'int', 'char', 'bool', 'double', 'float',
  };

  bool _hasUser(TypeRef t) => switch (t) {
        ListType(:final item) => _hasUser(item),
        OptionalType(:final inner) => _hasUser(inner),
        EnumType() || StructType() => true,
        PrimType() => false,
      };

  /// C++ spelling usable outside the module file, or null to leave it out.
  String? _spell(TypeExpr e, TypeRef t) {
    if (!_hasUser(t)) {
      final ok = e.tokens.every((tok) => tok.kind != TokKind.ident || _stdWords.contains(tok.text));
      return ok ? e.text : null;
    }
    String? rec(TypeRef t) => switch (t) {
          ListType(:final item) => rec(item) == null ? null : 'std::vector<${rec(item)}>',
          OptionalType(:final inner) => rec(inner) == null ? null : 'std::optional<${rec(inner)}>',
          EnumType(:final decl) => decl == null || decl.file == sourceFile ? null : decl.qualified,
          StructType(:final decl) => decl == null || decl.file == sourceFile ? null : decl.qualified,
          PrimType() => null,
        };
    return rec(t);
  }

  /// (member, C++ declaration) pairs included in the ref struct, or skipped (null).
  List<(String name, String? decl, String why)> _members(RModule m) => [
        for (final mem in m.members)
          if (mem is RProp)
            _entry(mem.name, mem.decl.type, mem.type, 'Prop')
          else if (mem is RList)
            _entry(mem.name, (mem.member as ListMember).itemType, mem.item, 'List'),
      ];

  (String, String?, String) _entry(String name, TypeExpr e, TypeRef t, String kind) {
    final spelled = _spell(e, t);
    return (
      name,
      spelled == null ? null : '::nativebind::$kind<$spelled>& $name;',
      spelled == null ? '`${e.text}` is declared in $sourceLabel' : '',
    );
  }

  String emitHeader() {
    final b = StringBuffer();
    void l([String s = '']) => b.writeln(s);
    l('// Generated by nativebind_generator from $sourceLabel. DO NOT EDIT.');
    l('// Typed access to its modules from other module files:');
    l('//');
    l('//     #include "${sourceLabel.replaceAll(RegExp(r'\.[^.]+$'), '')}.nb.hpp"');
    l('//     auto x = nativebind::ref::${modules.first.decl.name}::get();  // in onStart(), not in constructors');
    l();
    l('#pragma once');
    l();
    const fixed = ['<cstdint>', '<stdexcept>', '<string>', '<vector>'];
    final own = [for (final inc in includes) if (!fixed.contains(inc) && inc != '<nativebind/nativebind.hpp>') inc];
    for (final inc in own) {
      l('#include $inc');
    }
    l('#include <nativebind/nativebind.hpp>');
    l();
    for (final inc in fixed) {
      l('#include $inc');
    }
    l();
    l('namespace nativebind::ref {');
    for (final m in modules) {
      final name = m.decl.name;
      l();
      l('/// References to the props and lists of $name; valid while nativebind runs.');
      l('struct $name {');
      for (final (n, decl, why) in _members(m)) {
        l(decl == null ? '    // $n: not available here ($why)' : '    $decl');
      }
      l();
      if (m.decl.instanced) {
        l('    /// The instance spawned with [key]; throws std::out_of_range if there is none.');
        l('    static $name get(uint64_t key);');
      } else {
        l('    static $name get();');
      }
      l('};');
    }
    l();
    l('}  // namespace nativebind::ref');
    return b.toString();
  }

  /// Definitions of the `get()` functions, for the module's .nb.cpp.
  String emitDefinitions() {
    final b = StringBuffer();
    void l([String s = '']) => b.writeln(s);
    for (final m in modules) {
      final name = m.decl.name;
      final q = m.decl.qualified;
      final members = [for (final (n, decl, _) in _members(m)) if (decl != null) 'm.$n'];
      l();
      if (m.decl.instanced) {
        l('::nativebind::ref::$name nativebind::ref::$name::get(uint64_t key) {');
        l('    for ($q* p : ::nativebind::instances<$q>()) {');
        l('        if (p->key() != key) continue;');
        l('        auto& m = *p;');
        l('        return {${members.join(', ')}};');
        l('    }');
        l('    throw std::out_of_range("nativebind::ref::$name::get: no instance with that key");');
        l('}');
      } else {
        l('::nativebind::ref::$name nativebind::ref::$name::get() {');
        l('    auto& m = ::nativebind::singleton<$q>();');
        l('    return {${members.join(', ')}};');
        l('}');
      }
    }
    return b.toString();
  }
}
