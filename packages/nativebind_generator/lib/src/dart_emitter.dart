/// Dart names chosen for the types of one generator run (shared by all
/// emitted files so they agree).
class DartNames {
  final _types = <Object, String>{}; // EnumDecl/StructDecl -> Dart name
  final _owners = <String, Object>{};

  String typeName(Object decl, String cppName, SourceLoc loc, String? doc) {
    final existing = _types[decl];
    if (existing != null) return existing;
    final n = dartTypeNameOf(cppName, doc, loc);
    final other = _owners[n];
    if (other != null && other != decl) {
      throw GeneratorException(loc, 'two types would both be called `$n` in Dart',
          hint: 'rename one of them; Dart has no namespaces');
    }
    _owners[n] = decl;
    _types[decl] = n;
    return n;
  }
}

/// The Dart name of a C++ enum or struct: `/// @dart Name` in its doc
/// comment, or its C++ name in Dart style.
String dartTypeNameOf(String cppName, String? doc, SourceLoc loc) {
  final (rename, _) = dartNameFromDoc(doc);
  if (rename != null) {
    if (!RegExp(r'^[A-Za-z][A-Za-z0-9_]*$').hasMatch(rename) || dartReserved.contains(rename) || dartBuiltIn.contains(rename)) {
      throw GeneratorException(loc, '`@dart $rename` is not a valid Dart type name');
    }
  }
  final n = rename ?? dartType(cppName);
  checkNotCoreType(n, cppName, loc, renamable: true);
  return n;
}

/// A generated type named like a dart:core type the generated code uses
/// would hide it, and the generated Dart would not compile.
void checkNotCoreType(String dartName, String cppName, SourceLoc loc, {required bool renamable}) {
  if (!dartCoreTypesUsed.contains(dartName)) return;
  throw GeneratorException(loc, '`$cppName` would be `$dartName` in Dart, hiding the dart:core `$dartName` that generated code uses',
      hint: renamable ? 'add `/// @dart OtherName` to its doc comment to give it another Dart name' : 'rename it');
}

/// Emits `<name>.nb.dart`: the enums and structs declared in one file and
/// the typed proxies of its modules.
class DartEmitter {
  DartEmitter(this.analyzer, this.names,
      {required this.sourceLabel, required this.dartFileOf, required this.ownFile, required this.externalLibraryOf});

  final Analyzer analyzer;
  final DartNames names;
  final String sourceLabel;

  /// Dart file (basename) that defines the types declared in a C++ file.
  final String Function(String cppFile) dartFileOf;
  final String ownFile;

  /// Dart library that already defines the types of a C++ file
  /// (NATIVEBIND_DART_LIBRARY), or null if they are generated here.
  final String? Function(String cppFile) externalLibraryOf;
  final _external = <String, String>{}; // library uri -> import prefix

  final _b = StringBuffer();
  final _imports = <String>{};
  final _codecs = <String, String>{}; // expression -> hoisted name

  void _l([String s = '']) => _b.writeln(s);

  String emit({required List<EnumDecl> enums, required List<StructDecl> structs, required List<RModule> modules}) {
    final body = StringBuffer();
    final saved = _b.toString();
    assert(saved.isEmpty);

    for (final e in enums) {
      _enum(e);
    }
    for (final s in structs) {
      _struct(analyzer.structOf(s));
    }
    for (final m in modules) {
      _module(m);
    }
    if (_codecs.isNotEmpty) {
      _l();
      for (final MapEntry(:key, :value) in _codecs.entries) {
        _l('final $value = $key;');
      }
    }
    body.write(_b);

    final out = StringBuffer()
      ..writeln('// Generated by nativebind_generator from $sourceLabel. DO NOT EDIT.')
      ..writeln('//')
      ..writeln('// ignore_for_file: type=lint')
      ..writeln('// ignore_for_file: unused_import, unnecessary_import, unused_element')
      ..writeln()
      ..writeln("import 'package:nativebind/generated.dart' as \$p;");
    for (final i in _imports.toList()..sort()) {
      out.writeln("import '$i';");
    }
    for (final MapEntry(:key, :value) in _external.entries) {
      out.writeln("import '$key' as $value;");
    }
    out.write(body);
    return out.toString();
  }

  // ------------------------------------------------------------ types

  String _nameOf(TypeRef t) {
    switch (t) {
      case EnumType(:final decl):
        if (decl == null) return '\$p.${t.name}';
        final ext = _externalName(decl.file, decl.name, decl.doc, decl.loc);
        if (ext != null) return ext;
        _importFor(decl.file);
        return names.typeName(decl, decl.name, decl.loc, decl.doc);
      case StructType(:final decl):
        if (decl == null) return '\$p.${t.name}';
        final ext = _externalName(decl.file, decl.name, decl.doc, decl.loc);
        if (ext != null) return ext;
        _importFor(decl.file);
        return names.typeName(decl, decl.name, decl.loc, decl.doc);
      default:
        return dartTypeOf(t);
    }
  }

  /// `\$x0.Name` for a type defined by another Dart library, else null.
  String? _externalName(String cppFile, String cppName, String? doc, SourceLoc loc) {
    final lib = externalLibraryOf(cppFile);
    if (lib == null) return null;
    final prefix = _external.putIfAbsent(lib, () => '\$x${_external.length}');
    return '$prefix.${dartTypeNameOf(cppName, doc, loc)}';
  }

  void _importFor(String cppFile) {
    final f = dartFileOf(cppFile);
    if (f != ownFile) _imports.add(f);
  }

  String dartTypeOf(TypeRef t) => switch (t) {
        PrimType(prim: Prim.voidT) => 'void',
        PrimType(prim: Prim.boolT) => 'bool',
        PrimType(prim: Prim.intT) => 'int',
        PrimType(prim: Prim.doubleT) => 'double',
        PrimType(prim: Prim.stringT) => 'String',
        PrimType(prim: Prim.timeT) => 'DateTime',
        PrimType(prim: Prim.durationT) => 'Duration',
        ListType(:final item) => 'List<${dartTypeOf(item)}>',
        OptionalType(:final inner) => '${dartTypeOf(inner)}?',
        EnumType() || StructType() => _nameOf(t),
      };

  String codecOf(TypeRef t) {
    switch (t) {
      case PrimType(:final prim):
        return switch (prim) {
          Prim.voidT => '\$p.voidCodec',
          Prim.boolT => '\$p.boolCodec',
          Prim.intT => '\$p.intCodec',
          Prim.doubleT => '\$p.doubleCodec',
          Prim.stringT => '\$p.stringCodec',
          Prim.timeT => '\$p.timeCodec',
          Prim.durationT => '\$p.durationCodec',
        };
      case EnumType() || StructType():
        return '${_nameOf(t)}.\$codec';
      case ListType(:final item):
        return _hoist('\$p.ListCodec<${dartTypeOf(item)}>(${codecOf(item)})', 'list', t);
      case OptionalType(:final inner):
        return _hoist('\$p.OptionalCodec<${dartTypeOf(inner)}>(${codecOf(inner)})', 'optional', t);
    }
  }

  String _hoist(String expr, String kind, TypeRef t) =>
      _codecs.putIfAbsent(expr, () => '_\$${t.schema.replaceAll(RegExp('[^A-Za-z0-9]+'), '_').replaceAll(RegExp(r'_+$'), '')}');

  void _doc(String? doc, String indent) {
    if (doc == null || doc.trim().isEmpty) return;
    for (final line in doc.split('\n')) {
      _l(line.isEmpty ? '$indent///' : '$indent/// $line');
    }
  }

  // ------------------------------------------------------------ enums

  void _enum(EnumDecl e) {
    final name = names.typeName(e, e.name, e.loc, e.doc);
    final seen = <String>{};
    _l();
    _doc(dartNameFromDoc(e.doc).$2, '');
    _l('enum $name implements \$p.BindEnum {');
    for (final (k, v) in e.values.indexed) {
      final dn = dartEnumValue(v.name);
      if (!seen.add(dn)) {
        throw GeneratorException(e.loc, 'enumerators of ${e.name} collide as `$dn` in Dart');
      }
      final (label, doc) = labelFromDoc(v.doc);
      _doc(doc, '  ');
      _l('  $dn(${v.value}, ${dartString(label ?? humanLabel(v.name))})${k == e.values.length - 1 ? ';' : ','}');
    }
    _l();
    _l('  const $name(this.wire, this.label);');
    _l();
    _l('  /// Value of the C++ enumerator.');
    _l('  @override');
    _l('  final int wire;');
    _l();
    _l('  /// Display label: `///< @label ...` on the enumerator, or its name in words.');
    _l('  @override');
    _l('  final String label;');
    _l();
    _l('  static final \$p.Codec<$name> \$codec = \$p.EnumCodec<$name>(values, (e) => e.wire);');
    _l('}');
  }

  // ------------------------------------------------------------ structs

  void _struct(RStruct s) {
    final name = names.typeName(s.decl, s.decl.name, s.decl.loc, s.decl.doc);
    final fields = [
      for (final f in s.fields) (field: f, dart: dartMember(f.decl.name), type: dartTypeOf(f.type)),
    ];
    final seen = <String>{};
    for (final f in fields) {
      if (!seen.add(f.dart) || f.dart == '\$codec' || f.dart == 'copyWith') {
        throw GeneratorException(f.field.decl.loc, 'field `${f.field.decl.name}` of ${s.decl.name} clashes in Dart as `${f.dart}`');
      }
    }

    _l();
    _doc(dartNameFromDoc(s.decl.doc).$2, '');
    _l('final class $name {');
    _l('  const $name({');
    for (final f in fields) {
      final def = _default(f.field);
      if (def == null) {
        _l('    required this.${f.dart},');
      } else if (def == 'null') {
        _l('    this.${f.dart},');
      } else {
        _l('    this.${f.dart} = $def,');
      }
    }
    _l('  });');
    for (final f in fields) {
      _l();
      _doc(f.field.decl.doc, '  ');
      _l('  final ${f.type} ${f.dart};');
    }
    _l();
    _l('  /// A copy with the given fields replaced.');
    _l('  $name copyWith({');
    for (final f in fields) {
      _l('    ${f.type.endsWith('?') ? f.type : '${f.type}?'} ${f.dart},');
    }
    _l('  }) =>');
    _l('      $name(');
    for (final f in fields) {
      _l('        ${f.dart}: ${f.dart} ?? this.${f.dart},');
    }
    _l('      );');
    _l();
    _l('  @override');
    _l('  bool operator ==(Object other) =>');
    _l('      identical(this, other) ||');
    final eq = fields.map((f) => f.field.type is ListType
        ? '\$p.deepEquals(${f.dart}, other.${f.dart})'
        : '${f.dart} == other.${f.dart}');
    _l('      other is $name &&');
    final eqs = eq.toList();
    for (final (k, e) in eqs.indexed) {
      _l('          $e${k == eqs.length - 1 ? ';' : ' &&'}');
    }
    _l();
    _l('  @override');
    final hashes = fields.map((f) => f.field.type is ListType ? '\$p.deepHash(${f.dart})' : f.dart);
    _l('  int get hashCode => Object.hashAll([${hashes.join(', ')}]);');
    _l();
    _l('  @override');
    final str = fields.map((f) => '${f.dart}: \$${f.dart}').join(', ');
    _l("  String toString() => '$name($str)';");
    _l();
    _l('  static final \$p.Codec<$name> \$codec = \$p.StructCodec<$name>(');
    _l("    name: '$name',");
    _l('    fieldCount: ${fields.length},');
    _l('    decode: (f) => $name(');
    for (final (k, f) in fields.indexed) {
      _l('      ${f.dart}: ${codecOf(f.field.type)}.decode(f[$k]),');
    }
    _l('    ),');
    _l('    encode: (w, v) {');
    for (final f in fields) {
      _l('      ${codecOf(f.field.type)}.encode(w, v.${f.dart});');
    }
    _l('    },');
    _l('  );');
    _l('}');
  }

  /// Dart default for a struct field, or null if it must be required.
  String? _default(RField f) {
    final init = f.decl.init;
    final t = f.type;
    if (init == null || init.isEmpty) return _typeDefault(t);
    return _literal(init, t);
  }

  String? _typeDefault(TypeRef t) => switch (t) {
        PrimType(prim: Prim.boolT) => 'false',
        PrimType(prim: Prim.intT) => '0',
        PrimType(prim: Prim.doubleT) => '0.0',
        PrimType(prim: Prim.stringT) => "''",
        PrimType(prim: Prim.durationT) => 'Duration.zero',
        ListType() => 'const []',
        OptionalType() => 'null',
        EnumType() => _enumValue(t, null, wire: 0),
        _ => null, // time points and structs have no const default
      };

  String? _enumValue(EnumType t, String? cppName, {int? wire}) {
    final decl = t.decl;
    final dartName = _nameOf(t);
    if (decl != null) {
      for (final v in decl.values) {
        if ((cppName != null && v.name == cppName) || (cppName == null && v.value == wire)) {
          return '$dartName.${dartEnumValue(v.name)}';
        }
      }
    }
    return null;
  }

  String? _literal(List<Token> toks, TypeRef t) {
    var negative = false;
    var rest = toks;
    if (rest.length == 2 && rest.first.isPunct('-')) {
      negative = true;
      rest = rest.sublist(1);
    }
    switch (t) {
      case OptionalType(:final inner):
        if (rest.length == 1 && (rest.first.isIdent('nullopt'))) return 'null';
        if (rest.length == 3 && rest.first.isIdent('std') && rest.last.isIdent('nullopt')) return 'null';
        return _literal(toks, inner);
      case PrimType(prim: Prim.boolT):
        if (rest.length == 1 && (rest.first.isIdent('true') || rest.first.isIdent('false'))) return rest.first.text;
      case PrimType(prim: Prim.intT):
        if (rest.length == 1 && rest.first.kind == TokKind.number) {
          final v = parseCppInt(rest.first.text);
          if (v != null) return '${negative ? -v : v}';
        }
      case PrimType(prim: Prim.doubleT):
        if (rest.length == 1 && rest.first.kind == TokKind.number) {
          final v = _parseCppDouble(rest.first.text);
          if (v != null) return _dartDouble(negative ? -v : v);
        }
      case PrimType(prim: Prim.stringT):
        if (!negative && toks.isNotEmpty && toks.every((x) => x.kind == TokKind.string)) {
          final parts = toks.map(_cppStringValue).toList();
          if (parts.every((p) => p != null)) return dartString(parts.join());
        }
      case PrimType(prim: Prim.durationT):
        return _duration(toks);
      case EnumType():
        final ids = rest.where((x) => x.kind == TokKind.ident).toList();
        if (!negative && ids.isNotEmpty && rest.every((x) => x.kind == TokKind.ident || x.isPunct('::'))) {
          return _enumValue(t, ids.last.text);
        }
      case ListType():
        return null;
      default:
        return null;
    }
    return null;
  }

  static double? _parseCppDouble(String text) {
    var s = text.replaceAll("'", '');
    if (s.startsWith('0x') || s.startsWith('0X')) return null;
    s = s.replaceFirst(RegExp(r'[fFlL]$'), '');
    if (s.startsWith('.')) s = '0$s';
    if (s.endsWith('.')) s = '${s}0';
    return double.tryParse(s) ?? parseCppInt(text)?.toDouble();
  }

  static String _dartDouble(double v) {
    final s = v.toString();
    return s.contains('.') || s.contains('e') || s.contains('n') ? s : '$s.0';
  }

  /// `std::chrono::seconds(5)`, `seconds{5}`, `5s`, `100ms`, `2min`, `1h`
  String? _duration(List<Token> toks) {
    const ctor = {
      'hours': 'hours', 'minutes': 'minutes', 'seconds': 'seconds', 'milliseconds': 'milliseconds',
      'microseconds': 'microseconds',
    };
    const suffix = {'h': 'hours', 'min': 'minutes', 's': 'seconds', 'ms': 'milliseconds', 'us': 'microseconds'};
    if (toks.length == 1 && toks.first.kind == TokKind.number) {
      final m = RegExp(r"^([0-9']+)(h|min|s|ms|us)$").firstMatch(toks.first.text);
      if (m != null) return 'const Duration(${suffix[m.group(2)]}: ${m.group(1)!.replaceAll("'", '')})';
      return null;
    }
    final open = toks.indexWhere((x) => x.isPunct('(') || x.isPunct('{'));
    if (open < 1 || toks.length != open + 3) return null;
    final unit = ctor[toks[open - 1].text];
    final n = toks[open + 1].kind == TokKind.number ? parseCppInt(toks[open + 1].text) : null;
    if (unit == null || n == null) return null;
    return 'const Duration($unit: $n)';
  }

  static String? _cppStringValue(Token t) {
    var s = t.text;
    final q = s.indexOf('"');
    if (q < 0 || s.substring(0, q).contains('R')) return null; // raw strings: keep it simple
    s = s.substring(q + 1, s.length - 1);
    final b = StringBuffer();
    for (var k = 0; k < s.length; k++) {
      final c = s[k];
      if (c != '\\') {
        b.write(c);
        continue;
      }
      if (++k >= s.length) return null;
      switch (s[k]) {
        case 'n':
          b.write('\n');
        case 't':
          b.write('\t');
        case 'r':
          b.write('\r');
        case '\\' || '"' || "'":
          b.write(s[k]);
        case '0':
          b.write('\u0000');
        default:
          return null;
      }
    }
    return b.toString();
  }

  // ------------------------------------------------------------ modules

  void _module(RModule m) {
    final name = dartType(m.decl.name);
    checkNotCoreType(name, m.decl.name, m.decl.loc, renamable: false);
    final instanced = m.decl.instanced;
    final reserved = instanced ? {'instances', 'byKey', 'key', '\$type'} : {'instance', '\$type'};
    final used = <String, Member>{};
    String member(Member mem) {
      final d = dartModuleMember(mem.name);
      if (reserved.contains(d) || d.startsWith('\$')) {
        throw GeneratorException(mem.loc, '`${mem.name}` clashes with the generated $name.$d', hint: 'rename the member');
      }
      final prev = used[d];
      if (prev != null) {
        throw GeneratorException(mem.loc, '`${mem.name}` and `${prev.name}` are both `$d` in Dart');
      }
      used[d] = mem;
      return d;
    }

    _l();
    _doc(m.decl.doc, '');
    _l('final class $name extends \$p.ModuleProxy {');
    _l('  $name._(super.\$instance);');
    _l();
    _l('  static final \$p.ModuleType<$name> \$type = \$p.ModuleType<$name>(');
    _l("    name: '${m.decl.name}',");
    _l('    instanced: $instanced,');
    _l('    schema: _schema$name,');
    _l('    create: $name._,');
    final docs = [
      for (final mem in m.members)
        if ((mem is RProp || mem is RList || mem is RSignal || mem is RMethod) &&
            mem.member.doc != null &&
            mem.member.doc!.trim().isNotEmpty)
          (mem.name, docText(mem.member.doc!)),
    ];
    if (docs.isNotEmpty) {
      _l('    docs: {');
      for (final (n, d) in docs) {
        _l('      ${dartString(n)}: ${dartString(d)},');
      }
      _l('    },');
    }
    _l('  );');
    _l();
    if (instanced) {
      _l('  /// Live instances, ordered by key. Listen to it to follow additions and removals.');
      _l('  static \$p.BoundInstances<$name> get instances => \$type.instances;');
      _l();
      _l('  /// The instance spawned with [key], if it exists.');
      _l('  static $name? byKey(int key) => \$type.byKey(key);');
      _l();
      _l('  /// Key given to `nativebind::spawn` in C++.');
      _l('  int get key => \$key;');
    } else {
      _l('  /// The $name module.');
      _l('  static $name get instance => \$type.single;');
    }

    var propIndex = 0, listIndex = 0, signalIndex = 0, methodIndex = 0;
    for (final mem in m.members) {
      _l();
      _doc(mem.member.doc, '  ');
      switch (mem) {
        case RProp(:final type):
          final d = member(mem.member);
          final t = dartTypeOf(type);
          if (mem.decl.writable) {
            _l('  late final \$p.BoundProperty<$t> $d = \$property(${propIndex++}, ${codecOf(type)});');
          } else {
            _l('  late final \$p.BoundValue<$t> $d = \$value(${propIndex++}, ${codecOf(type)});');
          }
        case RList(:final item):
          final d = member(mem.member);
          _l('  late final \$p.BoundList<${dartTypeOf(item)}> $d = \$list(${listIndex++}, ${codecOf(item)});');
        case RSignal(:final args):
          final d = member(mem.member);
          final k = signalIndex++;
          if (args.isEmpty) {
            _l('  late final \$p.BoundSignal<void> $d = \$signal($k, (_) {});');
          } else if (args.length == 1) {
            _l('  late final \$p.BoundSignal<${dartTypeOf(args.first)}> $d =');
            _l('      \$signal($k, (a) => ${codecOf(args.first)}.decode(a[0]));');
          } else {
            final rec = '(${args.map(dartTypeOf).join(', ')})';
            final dec = [for (final (j, a) in args.indexed) '${codecOf(a)}.decode(a[$j])'].join(', ');
            _l('  late final \$p.BoundSignal<$rec> $d =');
            _l('      \$signal($k, (a) => ($dec));');
          }
        case RMethod(:final params, :final returns):
          final d = member(mem.member);
          final k = methodIndex++;
          final pnames = <String>[];
          for (final (j, p) in params.indexed) {
            var pn = dartMember(p.name ?? 'arg$j');
            while (pnames.contains(pn)) {
              pn = '${pn}_';
            }
            pnames.add(pn);
          }
          final sig = [for (final (j, p) in params.indexed) '${dartTypeOf(p.type)} ${pnames[j]}'].join(', ');
          final ret = dartTypeOf(returns);
          if (mem.decl.permission != null && (mem.member.doc == null || mem.member.doc!.isEmpty)) {
            _l('  /// Requires permission `${mem.decl.permission}` (checked by the C++ guard).');
          }
          if (params.isEmpty) {
            _l('  Future<$ret> $d() => \$invoke($k, null, ${codecOf(returns)});');
          } else {
            _l('  Future<$ret> $d($sig) => \$invoke($k, (w) {');
            for (final (j, p) in params.indexed) {
              _l('        ${codecOf(p.type)}.encode(w, ${pnames[j]});');
            }
            _l('      }, ${codecOf(returns)});');
          }
      }
    }
    final values = [for (final mem in m.members) if (mem is RProp) dartModuleMember(mem.name)];
    _l();
    _l('  /// Every property, in declaration order (for generic settings screens).');
    _l('  @override');
    if (values.isEmpty) {
      _l('  List<\$p.BoundValue<Object?>> get \$values => const [];');
    } else {
      _l('  late final List<\$p.BoundValue<Object?>> \$values = List.unmodifiable(<\$p.BoundValue<Object?>>[');
      for (final v in values) {
        _l('    $v,');
      }
      _l('  ]);');
    }
    _l('}');
    _l();
    final schema = schemaOf(m, analyzer).split('\n')..removeLast();
    _l('const _schema$name =');
    for (final (k, line) in schema.indexed) {
      _l('    ${dartString('$line\n')}${k == schema.length - 1 ? ';' : ''}');
    }
  }
}
